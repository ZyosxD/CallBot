import nodemailer from 'nodemailer';
import { config } from '../config/config.js';
import logger from '../utils/logger.js';

const transporter = nodemailer.createTransport({
  host: config.email.host,
  port: config.email.port,
  secure: config.email.secure,
  auth: {
    user: config.email.user,
    pass: config.email.pass,
  },
});

export const sendEmailReport = async (subject, htmlContent) => {
  if (!config.email.to || !config.email.user || !config.email.pass) {
    logger.warn('Email configuration is incomplete. Skipping email sending.');
    return;
  }

  try {
    const info = await transporter.sendMail({
      from: `"1Wire Assistant" <${config.email.user}>`,
      to: config.email.to,
      subject: subject,
      html: htmlContent,
    });
    logger.info(`Email sent: ${info.messageId}`);
  } catch (error) {
    logger.error('Error sending email:', error);
  }
};

export const sendSuccessEmail = async (appointmentDetails, callerId) => {
  const subject = `🟢 SUCCESS: Technical Assessment Scheduled - ${appointmentDetails.companyName}`;
  const html = `
    <h2>New Technical Assessment Scheduled!</h2>
    <p><strong>Contact Name:</strong> ${appointmentDetails.contactName}</p>
    <p><strong>Company Name:</strong> ${appointmentDetails.companyName}</p>
    <p><strong>Confirmed Phone:</strong> ${appointmentDetails.confirmedPhone}</p>
    <p><strong>Original Caller ID:</strong> ${callerId}</p>
    <p><strong>Appointment Time:</strong> ${appointmentDetails.appointmentTime}</p>
    <br/>
    <p><em>This appointment was generated by Sarah, the 1Wire Assistant.</em></p>
  `;
  await sendEmailReport(subject, html);
};

export const sendReportEmail = async (interactionDetails, callerId) => {
  const subject = `🟠 REPORT: Interaction Logged - Needs Follow-up`;
  const html = `
    <h2>Interaction Report</h2>
    <p><strong>Caller ID:</strong> ${callerId}</p>
    <p><strong>Reason:</strong> ${interactionDetails.reason}</p>
    <p><strong>Notes:</strong> ${interactionDetails.notes}</p>
    <br/>
    <p><em>Please review this interaction for potential follow-up.</em></p>
  `;
  await sendEmailReport(subject, html);
};
