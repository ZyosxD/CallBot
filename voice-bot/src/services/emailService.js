import nodemailer from 'nodemailer';
import { config } from '../config/config.js';
import logger from '../utils/logger.js';

const transporter = nodemailer.createTransport({
  host: config.smtp.host,
  port: config.smtp.port,
  secure: false, // true for 465, false for other ports
  auth: {
    user: config.smtp.user,
    pass: config.smtp.pass,
  },
});

export const sendEmail = async (type, data) => {
  try {
    let subject = '';
    let html = '';

    const callerId = data.callerId || 'Unknown';
    const confirmedPhone = data.confirmedPhone || 'Not Confirmed';

    if (type === 'success') {
      subject = `🟢 APPOINTMENT BOOKED - ${data.companyName}`;
      html = `
        <h2>New Appointment Scheduled</h2>
        <p><strong>Company:</strong> ${data.companyName}</p>
        <p><strong>Contact:</strong> ${data.contactName}</p>
        <p><strong>Time:</strong> ${data.appointmentTime}</p>
        <hr>
        <h3>Phone Verification</h3>
        <p><strong>Caller ID (Twilio):</strong> ${callerId}</p>
        <p><strong>Confirmed Phone:</strong> ${confirmedPhone}</p>
        <hr>
        <p><em>Generated by Sarah (1Wire Assistant)</em></p>
      `;
    } else if (type === 'report') {
      subject = `🟠 INTERACTION REPORT - ${callerId}`;
      html = `
        <h2>Interaction Report</h2>
        <p><strong>Result:</strong> ${data.status}</p>
        <p><strong>Notes:</strong> ${data.notes}</p>
        <hr>
        <h3>Phone Verification</h3>
        <p><strong>Caller ID (Twilio):</strong> ${callerId}</p>
        <p><strong>Confirmed Phone:</strong> ${confirmedPhone}</p>
        <hr>
        <p><em>Generated by Sarah (1Wire Assistant)</em></p>
      `;
    }

    const info = await transporter.sendMail({
      from: `"Sarah 1Wire" <${config.smtp.user}>`,
      to: config.smtp.notificationEmail,
      subject: subject,
      html: html,
    });

    logger.info(`Email sent: ${info.messageId}`);
  } catch (error) {
    logger.error('Error sending email:', error);
  }
};
