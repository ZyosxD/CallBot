import nodemailer from 'nodemailer';
import { config } from '../config/config.js';
import logger from '../utils/logger.js';

const transporter = nodemailer.createTransport({
  host: config.email.host,
  port: config.email.port,
  secure: config.email.port === 465, // true for 465, false for other ports
  auth: {
    user: config.email.user,
    pass: config.email.pass,
  },
});

const sendEmail = async (subject, htmlContent) => {
  if (!config.email.user || !config.email.pass) {
    logger.warn('SMTP credentials not configured. Skipping email send.');
    return;
  }

  try {
    const info = await transporter.sendMail({
      from: `"1Wire AI Assistant" <${config.email.user}>`,
      to: config.email.to,
      subject: subject,
      html: htmlContent,
    });
    logger.info(`Email sent: ${info.messageId}`);
  } catch (error) {
    logger.error('Error sending email:', error);
  }
};

export const sendSuccessEmail = async (leadData, callerId) => {
  const subject = `🟢 SUCCESS: Technical Assessment Scheduled - ${leadData.companyName}`;

  const originalCallerId = callerId && callerId !== 'unknown' ? callerId : 'Unknown/Outbound Client';

  const html = `
    <h2>New Technical Assessment Scheduled</h2>
    <p><strong>Company:</strong> ${leadData.companyName}</p>
    <p><strong>Contact Name:</strong> ${leadData.contactName}</p>
    <br>
    <p><strong>Appointment Time:</strong> ${leadData.appointmentTime}</p>
    <br>
    <h3>Phone Verification</h3>
    <p><strong>Original Caller ID:</strong> ${originalCallerId}</p>
    <p><strong>Verbally Confirmed Phone:</strong> ${leadData.confirmedPhone}</p>
    <hr>
    <p><em>Generated by Sarah (1Wire AI Assistant)</em></p>
  `;

  await sendEmail(subject, html);
};

